#!/usr/bin/env python3
"""Task 12.1: T8, E3's threshold-set breakdown (exploratory; spec §6).

One row per alpha: k, the smallest number of development honest-training
windows that, mixed into the calibration declared windows with R1's fit held
fixed, takes the unpaced co-location run to 0% at the new threshold; k's
share of the set and its seconds at the 5 s hop; the clean and contaminated
thresholds; and, at k, the flag rate of each co-location run and of
development honest training. Reads results/heldout/e3_calibration_breakdown.json
only.

    python3 scripts/table_t8.py   # writes figures/t8.tex
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
E3 = REPO / "results" / "heldout" / "e3_calibration_breakdown.json"
OUT = REPO / "figures" / "t8.tex"
RUNS = (("0p25", "0.25"), ("0p5", "0.5"), ("0p75", "0.75"))


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def main() -> None:
    e3 = json.loads(E3.read_text())
    n_cal = e3["calibration_windows"]
    lines = [r"\begin{tabular}{rrrrrrrrrr}", r"\toprule",
             r" & \multicolumn{3}{c}{honest windows added} & & & "
             r"\multicolumn{4}{c}{flagged at $\tau'$ (\%)} \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){7-10}",
             r"$\alpha$ & $k$ & share (\%) & s & $\tau_\alpha$ & $\tau'$ & "
             + " & ".join(f"$\\rho = {r}$" for _, r in RUNS) + r" & honest \\",
             r"\midrule"]
    for a, b in e3["breakdown_by_alpha"].items():
        r = b["rates"]
        cells = [a, str(b["n_windows"]), pct(b["share_of_calibration"]),
                 str(b["seconds_at_hop"]), f"{b['tau_clean']:.3f}", f"{b['tau']:.3f}"]
        cells += [pct(r[f"co-location panel-mixture-concurrent-{k}"]) for k, _ in RUNS]
        cells.append(pct(r["honest training"]))
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.write_text("% generated by scripts/table_t8.py from "
                   f"e3_calibration_breakdown.json ({e3['repo_commit'][:7]}; "
                   f"r1_scores.json {e3['sources']['r1_scores.json'][:7]}); "
                   f"{n_cal} calibration windows\n" + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
