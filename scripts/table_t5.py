#!/usr/bin/env python3
"""Task 7.6: T5 as a markdown table, from results/gk/t5.json alone.
Task 8.5: also the bare LaTeX table the paper inputs; its caveats go in the
paper's caption.

    python3 scripts/table_t5.py      # writes results/gk/t5.md and figures/t5.tex
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "code"))
import gk  # noqa: E402  (corpus-free)

T5 = REPO / "results" / "gk" / "t5.json"
OUT = REPO / "results" / "gk" / "t5.md"
TEX = REPO / "figures" / "t5.tex"


def pct(v: float | None) -> str:
    return "—" if v is None else f"{100 * v:.1f}%"


def ci(v: list | None) -> str:
    return "" if not v else f" [{100 * v[0]:.1f}, {100 * v[1]:.1f}]"


def fir_gain_db(f_hz: float) -> float:
    """Gain of `gk.decimate` on a unit tone at f_hz (aliased if above Nyquist)."""
    t = np.arange(gk.DOWN * 400) / gk.FS_IN
    y = gk.decimate(np.sin(2 * np.pi * f_hz * t))[2000:-2000]   # f_hz must avoid 100 kHz (Nyquist)
    return float(20 * np.log10(np.sqrt(2) * np.sqrt(np.mean(y.astype(np.float64) ** 2))))


def called(r: dict, cond: str) -> str:
    """How a forest classed one inference condition's windows, e.g. "non-ai 850/850"."""
    pred = r["gate_inference"]["by_condition"][cond]["predicted"]
    n = sum(pred.values())
    return ", ".join(f"{c} {k}/{n}" for c, k in sorted(pred.items(), key=lambda kv: -kv[1]))


def tex_pct(v: float | None) -> str:
    return "--" if v is None else f"{100 * v:.1f}"


def write_tex(t5: dict) -> None:
    """Gate rows and co-location per run, one column per forest."""
    forests, order = t5["forests"], ["hardened", "genuine"]
    lines = [r"\begin{tabular}{lrr}", r"\toprule",
             r"Our windows & G\&K hardened & G\&K genuine \\", r"\midrule"]

    def row(name, cell):
        lines.append(f"{name} & " + " & ".join(cell(forests[f]) for f in order) + r" \\")

    row(r"honest training ($\geq 80$\%)",
        lambda r: tex_pct(r["gate"]["training_detection"]))
    for cond in ("serving-decode", "serving-prefill"):
        row("declared " + cond.removeprefix("serving-"),
            lambda r, c=cond: tex_pct(r["gate_inference"]["by_condition"][c]["flag_rate"]))
    row(r"declared, decode + prefill ($\leq 20$\%)", lambda r: tex_pct(r["gate"]["inference_flag_rate"]))
    lines.append(r"\midrule")
    runs = sorted({run for f in order if isinstance(forests[f]["co-location"], dict)
                   for run in forests[f]["co-location"]["per_run"]})
    for run in runs:
        label = run.rsplit("-", 1)[-1]
        row(r"co-location, $\rho = " + label.replace("p", ".") + "$",
            lambda r, run=run: tex_pct(r["co-location"]["per_run"][run]["detection"])
            if isinstance(r["co-location"], dict) else "not scored")
    lines += [r"\bottomrule", r"\end{tabular}"]
    TEX.write_text("% generated by scripts/table_t5.py from results/gk/t5.json"
                   f" (repo_commit {t5['repo_commit'][:7]})\n"
                   "% percent of windows flagged training; co-location over windows with >= 1 complete step\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {TEX.relative_to(REPO)}")


def main() -> None:
    t5 = json.loads(T5.read_text())
    forests = t5["forests"]
    order = ["hardened", "genuine"]
    head = "| Row | " + " | ".join(f"G&K {f}{' (headline)' if f == t5['headline_forest'] else ''}"
                                   for f in order) + " |"
    oc, rep = t5["own_check"], t5["own_check"]["gk_reported"]
    coloc = [forests[f]["co-location"] for f in order if isinstance(forests[f]["co-location"], dict)]
    n_coloc = coloc[0]["pooled"]["n_runs"] if coloc else 0
    gains = ", ".join(f"{fir_gain_db(f * 1e3):.1f} dB at {f} kHz" for f in (90, 110, 120))
    lines = [
        "# T5: G&K-trained forests on our windows",
        "",
        f"Generated from `results/gk/t5.json` ({t5['generated_at']}, repo `{t5['repo_commit'][:7]}`). "
        "Rates are windows flagged `training`; detection is over windows containing a complete "
        "optimizer step.",
        "",
        f"- **Own-data check, a disclosed deviation.** On G&K's own traces this chain gives mean "
        f"macro-F1 {oc['macro_f1_mean']:.3f} [{oc['macro_f1_range'][0]:.3f}, "
        f"{oc['macro_f1_range'][1]:.3f}] and accuracy {oc['accuracy_mean']:.3f} over "
        f"{oc['n_runs']} runs; G&K report macro-F1 {rep['macro_f1']} / accuracy {rep['accuracy']}: "
        f"{rep['protocol']}. "
        "Pre-registration §9/§11 required their accuracy to be reproduced before our windows were "
        "scored. It was not, and T5 was scored anyway (spec §12, 2026-10-09). Shuffled-label "
        f"control: macro-F1 {oc['negative_control']['macro_f1']:.3f}.",
        "- **What the inference gate measures.** " + "; ".join(
            f"{f}: decode → {called(forests[f], 'serving-decode')}, prefill → "
            f"{called(forests[f], 'serving-prefill')}" for f in order)
        + "." + (lambda fs: f" Decode stays under the gate by being called non-AI, not inference "
                 f"({', '.join(fs)})." if fs else "")(
            [f for f in order if called(forests[f], "serving-decode").startswith("non-ai")
             and forests[f]["gate_inference"]["by_condition"]["serving-decode"]["flag_rate"] == 0])
        + "".join(
            f" {f} flags all prefill and passes only because decode outnumbers it."
            for f in order if forests[f]["gate"]["passed"]
            and forests[f]["gate_inference"]["by_condition"]["serving-prefill"]["flag_rate"] == 1),
        f"- **Co-location rests on {n_coloc} runs.** Each run is all-or-nothing, so the within-run "
        "intervals are degenerate; the pooled row carries the run-level interval.",
        f"- **Different chains.** G&K traces are decimated 9.765625 MS/s → 200 kS/s through an "
        f"anti-alias FIR ({gains}); ours are streamed at 199,808 S/s without one, so features above "
        "~10 kHz differ systematically between the datasets.",
        "",
        head,
        "|---|" + "---|" * len(order),
    ]

    def row(name: str, cell) -> None:
        lines.append(f"| {name} | " + " | ".join(cell(forests[f]) for f in order) + " |")

    row("Gate: honest `training` (≥ 80%)",
        lambda r: pct(r["gate"]["training_detection"]) + ci(r["gate_training"]["pooled"].get("detection_ci95")))
    row("Gate: declared inference, decode + prefill (≤ 20%)",
        lambda r: pct(r["gate"]["inference_flag_rate"]))
    for cond in ("serving-decode", "serving-prefill"):
        row(f"  {cond}",
            lambda r, c=cond: pct(r["gate_inference"]["by_condition"].get(c, {}).get("flag_rate")))
    row("Gate verdict", lambda r: "pass" if r["gate"]["passed"] else "**fail**")
    row("Honest group, all conditions (reported)",
        lambda r: pct(r["honest_group"]["pooled"]["detection"]))
    runs = sorted({run for f in order if isinstance(forests[f]["co-location"], dict)
                   for run in forests[f]["co-location"]["per_run"]})
    if not runs:
        row("Co-location", lambda r: "not scored (gate failed)")
    else:
        row("Co-location, pooled over runs (run-level interval)",
            lambda r: pct(r["co-location"]["pooled"]["detection"])
            + ci(r["co-location"]["pooled"]["detection_ci95"])
            if isinstance(r["co-location"], dict) else "not scored (gate failed)")
    for run in runs:
        def cell(r, run=run):
            c = r["co-location"]
            if not isinstance(c, dict):
                return "not scored (gate failed)"
            v = c["per_run"][run]
            return pct(v["detection"]) + ci(v["detection_ci95"])
        row(f"Co-location `{run}`", cell)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    write_tex(t5)


if __name__ == "__main__":
    main()
