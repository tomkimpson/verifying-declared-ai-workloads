#!/usr/bin/env python3
"""Task 5.1: achieved test false-positive rate of every classifier fit, as a
LaTeX appendix table (pre-registration §4: the headline row is the
co-location-held-out fit; the other four fits' rates go in an appendix), from
results/heldout/h2.json. R1's row is given for reference. Writes
figures/fpr_fits.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "results" / "heldout" / "h2.json"
OUT = REPO / "figures" / "fpr_fits.tex"
WORKLOADS = ("serving-decode", "idle")


def cell(e: dict) -> str:
    lo, hi = e["fpr_ci95"]
    return f"{100 * e['fpr']:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]"


def main() -> None:
    h = json.loads(SRC.read_text())
    lines = [r"\begin{tabular}{lrrr}", r"\toprule",
             r"Detector & threshold & FPR decode (\%) & FPR idle (\%) \\", r"\midrule",
             f"$s_R$ & {h['r1']['threshold']:.4f} & "
             + " & ".join(cell(h["r1"]["test_fpr"][w]) for w in WORKLOADS) + r" \\"]
    for fit, v in h["classifier"].items():
        lines.append(rf"$s_C^{{\mathrm{{dev}}}}$, {fit} held out & {v['threshold']:.4f} & "
                     + " & ".join(cell(v["test_fpr"][w]) for w in WORKLOADS) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("% generated by scripts/table_fpr_fits.py from results/heldout/h2.json"
                   f" (repo_commit {h['repo_commit'][:7]})\n"
                   "% achieved FPR on test declared windows; [95% interval: decode 2 runs,\n"
                   "% stratified block (within-run only); idle 4 runs, run-level]\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
