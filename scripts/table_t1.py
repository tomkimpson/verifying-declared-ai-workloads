#!/usr/bin/env python3
"""Task 4.3: T1 as a LaTeX table, from results/coverage/t1.json (spec §6).

One row per strategy group, with co-location broken out per run (amendment
2026-10-02e). Columns: level 1 (replica), level 2 with the group held out,
and level 2 seen (run held out within the group). Pooled rates carry the
interval §8 of the pre-registration assigns by run count. Writes figures/t1.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "results" / "coverage" / "t1.json"
OUT = REPO / "figures" / "t1.tex"
GROUPS = ("time-sharing", "jitter", "padding", "power cap", "co-location")
METHOD = {"run-level": "r", "within-run block": "w"}


def cell(entry, run=None) -> str:
    if entry is None:
        return "n/a"
    if run is not None:
        e = entry["per_run"][run]
        lo, hi = e["detection_ci95"]
        return f"{100 * e['detection']:.1f} [{100 * lo:.0f}, {100 * hi:.0f}]$^w$"
    p = entry["pooled"]
    lo, hi = p["detection_ci95"]
    tag = METHOD.get(p["interval_method"], "s")
    return f"{100 * p['detection']:.1f} [{100 * lo:.0f}, {100 * hi:.0f}]$^{tag}$"


def main() -> None:
    t = json.loads(SRC.read_text())
    l1, l2, seen = (t[k] for k in ("level1_replica", "level2_held_out",
                                   "level2_seen_leave_one_run_out"))
    lines = [r"\begin{tabular}{lrrrr}", r"\toprule",
             r"Strategy & runs & $s_C^{\mathrm{rep}}$ & $s_C^{\mathrm{hard}}$, held out & $s_C^{\mathrm{hard}}$, seen \\",
             r"\midrule",
             f"honest training & {l1['honest']['pooled']['n_runs']} & {cell(l1['honest'])} & -- & -- \\\\"]
    for g in GROUPS:
        lines.append(f"{g} & {l2[g]['pooled']['n_runs']} & {cell(l1[g])} & {cell(l2[g])} & {cell(seen[g])} \\\\")
    for run in sorted(l2["co-location"]["per_run"]):
        name = r"\quad $\rho = " + run.rsplit("-", 1)[-1].replace("p", ".") + "$"
        lines.append(f"{name} & 1 & {cell(l1['co-location'], run)} & {cell(l2['co-location'], run)} "
                     f"& {cell(seen['co-location'], run)} \\\\")
    ref = t["gk_reference"]
    lo, hi = ref["detection_range"]
    lines += [r"\midrule",
              f"G\\&K worst held-out ({ref['strategy']}) & -- & -- & {100 * lo:.0f}--{100 * hi:.0f} & -- \\\\",
              r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("% generated by scripts/table_t1.py from results/coverage/t1.json"
                   f" (t1.json repo_commit {t['repo_commit'][:7]})\n"
                   "% detection (%) on windows with >= 1 complete step; [95% interval];\n"
                   "% r run-level, s stratified block (within-run only), w within-run block\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
