#!/usr/bin/env python3
"""Task 5.2: T2 as a LaTeX table, from results/monitor/false_alarms.json (spec §6).

One block per background (never pooled), one row per detector: onsets, F
with its Poisson-model upper bound, and A with its approximate block
interval. Writes figures/t2.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "results" / "monitor" / "false_alarms.json"
OUT = REPO / "figures" / "t2.tex"
NAMES = {"r1": "$s_R$", "classifier": r"$s_C^{\mathrm{dev}}$"}
#: The OR monitor ("either") is not shown (amendment 2026-11-16b).
#: Short enough for one column: each background heads its own block.
#: Display name per background key; the test day's declared inference is decode only.
SHOWN = {"declared inference": "declared decode"}


def main() -> None:
    t = json.loads(SRC.read_text())
    lines = [r"\setlength{\tabcolsep}{3pt}", r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
             r"Detector & onsets & $F$ (/h) & upper (/h) & $A$ (\%) \\",
             r"\midrule"]
    for bg, v in t["backgrounds"].items():
        e = v[next(iter(NAMES))]["exposure_h"]
        lines.append(rf"\multicolumn{{5}}{{@{{}}l}}{{\emph{{{SHOWN.get(bg, bg)}}}, $E = {e:.3f}$ h}} \\")
        for k in NAMES:
            x = v[k]
            lo, hi = x["A_ci95_block_approx"]
            lines.append(f"\\quad {NAMES[k]} & {x['onsets']} & {x['F_per_h']:.1f} & "
                         f"{x['F_upper95_poisson_model']:.1f} & {100 * x['A']:.1f} "
                         f"[{100 * lo:.1f}, {100 * hi:.1f}] \\\\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("% generated by scripts/table_t2.py from results/monitor/false_alarms.json"
                   f" (repo_commit {t['repo_commit'][:7]})\n"
                   "% 3-of-5 monitor on 1 s-hop test windows; upper bound: exact Poisson model;\n"
                   "% A interval: approximate onset-block bootstrap (under-covers)\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
