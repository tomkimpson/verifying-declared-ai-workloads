#!/usr/bin/env python3
"""The 25 window features, as a LaTeX table (third-party review).

Feature names in the order the detectors use them, from
results/heldout/thresholds.json, grouped by the signal they are computed on:
the 2 ms RMS envelope e(t) or the raw waveform. Writes figures/t_features.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "results" / "heldout" / "thresholds.json"
OUT = REPO / "figures" / "t_features.tex"
SOURCE = {"env": r"envelope $e(t)$", "wav": "raw waveform"}


def tt(name: str) -> str:
    return r"\texttt{" + name.replace("_", r"\_") + "}"


def main() -> None:
    t = json.loads(SRC.read_text())
    feats = t["features"]
    lines = [r"\begin{tabular}{l>{\raggedright\arraybackslash}p{0.75\linewidth}}", r"\toprule",
             r"Computed on & Features \\", r"\midrule"]
    for prefix, name in SOURCE.items():
        mine = [f for f in feats if f.startswith(prefix + "_")]
        lines.append(f"{name} ({len(mine)}) & " + ", ".join(map(tt, mine)) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    assert sum(f.startswith(tuple(p + "_" for p in SOURCE)) for f in feats) == len(feats)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("% generated by scripts/table_features.py from results/heldout/thresholds.json"
                   f" (repo_commit {t['repo_commit'][:7]})\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
