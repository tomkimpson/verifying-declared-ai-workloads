#!/usr/bin/env python3
"""Task 5.4: T4 as a LaTeX table, from results/robustness/t4.json (spec §6).

One row per variant: H2's co-location detection (R1 Z, classifier X') and
R1's test false-positive rates where the variant changes them, and H3's R1
monitor (onsets on test declared inference and idle, the lowest per-cell
headline episode detection, Lmin).
The decode-only declaration has two rows, one per calibration (amendment
2026-10-05b).
Sensitivity only; no row replaces a headline. Writes figures/t4.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "results" / "robustness" / "t4.json"
OUT = REPO / "figures" / "t4.tex"


def pct(v) -> str:
    return "--" if v is None else f"{100 * v:.1f}"


def episode_cells(h3: dict) -> str:
    """Lowest per-cell headline episode detection and Lmin."""
    ep = h3["episodes"]
    low = min(c["rate"] for c in ep["cells"].values())
    lmin = "n.e." if ep["Lmin_s"] is None else f"{ep['Lmin_s']:g}"
    return f"{pct(low)} & {lmin}"


def h3_cells(h3: dict) -> str:
    fa = h3["false_alarms"]
    return (f"{fa['declared inference']['onsets']} & {fa['idle']['onsets']} & "
            f"{episode_cells(h3)}")


def main() -> None:
    t = json.loads(SRC.read_text())
    lines = [r"\begin{tabular}{lrrrrrrrr}", r"\toprule",
             r"Variant & $Z$ & $X'$ & FPR dec. & FPR idle & onsets dec. & onsets idle "
             r"& lowest cell (\%) & $L_\mathrm{min}$ (s) \\", r"\midrule"]
    for a, v in t["alpha_sweep"].items():
        h2 = v["h2"]
        lines.append(f"$\\alpha = {a}$ & {pct(h2['r1']['co-location']['pooled'])} & "
                     f"{pct(h2['classifier']['co-location']['pooled'])} & "
                     f"{pct(h2['r1_test_fpr']['serving-decode'])} & {pct(h2['r1_test_fpr']['idle'])} & "
                     f"{h3_cells(v['h3']['r1'])} \\\\")
    lines.append(r"\midrule")
    for p, v in t["persistence"].items():
        lines.append(f"persistence {p} & -- & -- & -- & -- & {h3_cells(v['r1'])} \\\\")
    lines.append(r"\midrule")
    m = t["misspecified_declaration"]
    for cal, name in (("pooled", "pooled calibration"), ("declared", "decode calibration")):
        v = m[cal]
        fa = v["h3"]["r1"]["false_alarms"]
        # Idle is undeclared under this declaration: stress, not a false positive
        # (dagger). Under the pooled calibration idle sets the threshold, so its
        # rate is circular and not shown (amendment 2026-10-05b).
        idle = "--$^\\ddagger$" if cal == "pooled" else f"{pct(v['h2']['r1_test_fpr']['idle'])}$^\\dagger$"
        idle_on = f"{fa['idle']['onsets']}$^\\dagger$"
        lines.append(f"decode-only declaration, {name} & {pct(v['h2']['r1']['co-location']['pooled'])} & -- & "
                     f"{pct(v['h2']['r1_test_fpr']['serving-decode'])} & {idle} & "
                     f"{fa['declared inference']['onsets']} & {idle_on} & "
                     f"{episode_cells(v['h3']['r1'])} \\\\")
    lines.append(f"CUSUM on $s_R$ & -- & -- & -- & -- & {h3_cells(t['cusum']['h3']['r1'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("% generated by scripts/table_t4.py from results/robustness/t4.json"
                   f" (repo_commit {t['repo_commit'][:7]})\n"
                   "% sensitivity only. Z, X': co-location detection (%); FPR: R1 on test declared\n"
                   "% windows (%); onsets: R1 3-of-5 monitor; lowest cell: smallest per-cell headline episode\n"
                   "% detection (onset-only where the gap guard fires); n.e. not established.\n"
                   "% CUSUM is R1 only: the classifier's calibration scores are almost all 0 (amendment 2026-10-05)\n"
                   "% decode-only rows: dagger, idle is undeclared (stress; its time in alarm A is in the caption);\n"
                   "% double dagger, pooled-calibration idle rate omitted: idle set the threshold (circular)\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
