#!/usr/bin/env python3
"""Task 8.5: T3, the S1 replication, as a LaTeX table (spec §6, appendix A).

S1's result lives in the corpus repo (amodo `results/replication/
classification.json`), which this repo never writes to. It is read from the
vendored, hash-checked copy at the pinned corpus commit (vendor/amodo). The cited fields are copied, with the source path, commit and
SHA-256, to results/replication/t3.json, which the paper's number macros read.

    python3 scripts/table_t3.py   # writes results/replication/t3.json and figures/t3.tex
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC_PATH = "results/replication/classification.json"
OUT_JSON = REPO / "results" / "replication" / "t3.json"
OUT_TEX = REPO / "figures" / "t3.tex"

# code/corpus.py holds the pin but cannot be imported without the archive;
# read the two constants from its source instead of repeating them.
_CORPUS_SRC = (REPO / "code" / "corpus.py").read_text()
CORPUS_COMMIT = re.search(r'^CORPUS_COMMIT = "([0-9a-f]{40})"', _CORPUS_SRC, re.M).group(1)
#: Vendored, unmodified copy of amodo-power-experiments at CORPUS_COMMIT (see code/corpus.py).
CORPUS_REPO = REPO / "vendor" / "amodo"



def shown(label: str) -> str:
    """Class label as the paper writes it."""
    return "non-AI" if label == "non-ai" else label

def main() -> None:
    raw = (CORPUS_REPO / SRC_PATH).read_bytes()
    c = json.loads(raw)
    ts = c["two_stage"]
    out = {
        "generated_by": "scripts/table_t3.py",
        "spec_task": "8.5",
        "source": {"repo": "amodo-power-experiments", "path": SRC_PATH,
                   "corpus_commit": CORPUS_COMMIT, "sha256": hashlib.sha256(raw).hexdigest()},
        "n_traces": c["n_traces"], "n_features": c["n_features"], "n_groups": c["n_groups"],
        "split": c["split"], "forest_kwargs": c["forest_kwargs"],
        "two_stage": {k: ts[k] for k in ("macro_f1", "accuracy", "per_class", "labels",
                                         "confusion_matrix")},
        "label_shuffle_control": c["label_shuffle_control"],
    }
    OUT_JSON.parent.mkdir(exist_ok=True)
    OUT_JSON.write_text(json.dumps(out, indent=1) + "\n")

    labels = ts["labels"]
    lines = [r"\begin{tabular}{l" + "r" * len(labels) + "r}", r"\toprule",
             r"true $\downarrow$ / predicted $\rightarrow$ & " + " & ".join(map(shown, labels)) + r" & $F_1$ \\",
             r"\midrule"]
    for lab, row in zip(labels, ts["confusion_matrix"]):
        lines.append(f"{shown(lab)} & " + " & ".join(map(str, row))
                     + f" & {ts['per_class'][lab]['f1']:.3f} \\\\")
    lines += [r"\midrule",
              f"macro-$F_1$ & \\multicolumn{{{len(labels) + 1}}}{{r}}{{{ts['macro_f1']:.3f}}} \\\\",
              r"\bottomrule", r"\end{tabular}"]
    OUT_TEX.write_text(f"% generated by scripts/table_t3.py from amodo {SRC_PATH} at {CORPUS_COMMIT[:7]}\n"
                       f"% two-stage forest, {c['split']}\n" + "\n".join(lines) + "\n")
    print(f"wrote {OUT_JSON.relative_to(REPO)} and {OUT_TEX.relative_to(REPO)}")


if __name__ == "__main__":
    main()
