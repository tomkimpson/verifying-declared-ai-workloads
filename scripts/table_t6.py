#!/usr/bin/env python3
"""Task 10.3: T6, what each detector learns from (spec §6, main §3.2).

One row per detector: the replica (level 1), the no-evasion fit (E2),
s_C^dev (the H2 classifier, co-location held out) and R1. Columns: what its
fit data hold (declared workloads, honest training, evasion strategies,
non-AI work), its detection of the unpaced co-location run at tau_alpha, its
achieved false-positive rate on test declared decode at tau_alpha, and what an
alarm means.

"Learns from" is read from each fit's run manifest: each run's condition comes
from the committed window manifest (results/windows/manifest.json), and its
group from code/groups.py (spec D2). The replica is fitted on the replication traces of
the published design (results/replication/t3.json), none of ours. Numbers come
from results/heldout/operating_point.json (classifiers) and
results/heldout/h2.json (R1).

    python3 scripts/table_t6.py   # writes figures/t6.tex
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "code"))

import groups  # noqa: E402

OP = REPO / "results" / "heldout" / "operating_point.json"
H2 = REPO / "results" / "heldout" / "h2.json"
R1 = REPO / "results" / "heldout" / "r1_scores.json"
T3 = REPO / "results" / "replication" / "t3.json"
MANIFEST = REPO / "results" / "windows" / "manifest.json"
OUT = REPO / "figures" / "t6.tex"
UNPACED = "panel-mixture-concurrent-0p5"
COLUMNS = ("declared", "honest training", "evasions", "non-AI")
YES, NO, PUBLISHED = r"\checkmark", "--", "pub."


def conditions() -> dict[str, str]:
    """run_id -> condition, from the committed window manifest."""
    return {c["run_id"]: c["condition"]
            for c in json.loads(MANIFEST.read_text())["captures"]}


def learns_from(runs: list[str], cond: dict[str, str]) -> dict[str, bool]:
    """Which kinds of data a fit's runs hold (spec D2 groups)."""
    kinds = set()
    for r in runs:
        c = cond[r]
        g = groups.group(c)
        if c in groups.DECLARED:
            kinds.add("declared")
        elif g == "honest":
            kinds.add("honest training")
        elif g == "negatives":
            kinds.add("non-AI")
        else:
            kinds.add("evasions")
    return {k: k in kinds for k in COLUMNS}


def main() -> None:
    op, h2, r1 = (json.loads(p.read_text()) for p in (OP, H2, R1))
    t3 = json.loads(T3.read_text())
    cond = conditions()
    replica_classes = set(t3["two_stage"]["labels"])
    replica = {"declared": "inference" in replica_classes,
               "honest training": "training" in replica_classes,
               "evasions": False, "non-AI": "non-ai" in replica_classes}
    rows = [
        ("replica", replica, True, op["replica"], "training"),
        ("no-evasion fit", learns_from(op["no_evasion_fit_manifest"], cond), False,
         op["no_evasion"], "training"),
        (r"$s_C^{\mathrm{dev}}$", learns_from(op["classifier_fit_manifest"], cond), False,
         op["classifier"], "training"),
        ("$s_R$", learns_from(r1["fit_runs"]["r1"], cond), False, None, "undeclared"),
    ]
    lines = [r"\begin{tabular}{l" + "c" * len(COLUMNS) + "rrl}", r"\toprule",
             r" & \multicolumn{" + str(len(COLUMNS)) + r"}{c}{learns from} & & & \\",
             r"\cmidrule(lr){2-" + str(len(COLUMNS) + 1) + "}",
             "detector & " + " & ".join(COLUMNS)
             + r" & $d_{\mathrm{unthrottled}}(\tau_\alpha)$ & FPR decode & alarm means \\",
             r"\midrule"]
    for name, learns, pub, entry, meaning in rows:
        if entry is None:  # R1: the pre-registered H2 run
            det = h2["headline"]["Z_per_run"][UNPACED]
            fpr = h2["headline"]["r1_test_fpr"]["serving-decode"]
        else:
            det = entry["tau_alpha"]["detection_per_run"][UNPACED]
            fpr = entry["tau_alpha"]["fpr"]["test"]["serving-decode"]["fpr"]
        cells = [(PUBLISHED if pub else YES) if learns[k] else NO for k in COLUMNS]
        lines.append(f"{name} & " + " & ".join(cells)
                     + f" & {100 * det:.1f}\\% & {100 * fpr:.1f}\\% & {meaning} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    manifest = json.loads(MANIFEST.read_text())
    OUT.write_text("% generated by scripts/table_t6.py from (repo_commit of each source):\n"
                   f"% operating_point.json {op['repo_commit'][:7]}, h2.json "
                   f"{h2['repo_commit'][:7]}, r1_scores.json {r1['repo_commit'][:7]},\n"
                   f"% windows/manifest.json {manifest['repo_commit'][:7]}, replication/t3.json "
                   f"(amodo {t3['source']['corpus_commit'][:7]})\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
