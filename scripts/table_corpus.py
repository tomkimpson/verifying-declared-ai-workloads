#!/usr/bin/env python3
"""The corpus per workload and split, as a LaTeX table (third-party review).

Runs, scored hours and 5 s-hop windows per strategy group and split, from
results/windows/manifest.json. Declared work is broken out per workload, so
the table shows what the calibration set holds. Writes figures/t_corpus.tex.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "code"))
import groups  # noqa: E402

SRC = REPO / "results" / "windows" / "manifest.json"
OUT = REPO / "figures" / "t_corpus.tex"
SPLITS = ("development", "test", "calibration")
SHORT = {"development": "dev", "test": "test", "calibration": "cal"}
#: Row order and display names.
ROWS = (("honest", "honest training"), ("time-sharing", "time-sharing"),
        ("co-location", "co-location"), ("jitter", "jitter"), ("padding", "padding"),
        ("power cap", "power cap"), ("serving-decode", "declared decode"),
        ("serving-prefill", "declared prefill"), ("idle", "declared idle"),
        ("non-AI", "non-AI work"))


def row_key(condition: str) -> str:
    """Strategy group, with declared work split per workload."""
    if condition in groups.DECLARED:
        return condition
    g = groups.group(condition)
    return "non-AI" if g == "negatives" else g


def main() -> None:
    m = json.loads(SRC.read_text())
    cell = defaultdict(lambda: [0, 0.0, 0])  # (row, split) -> runs, hours, windows
    for c in m["captures"]:
        x = cell[(row_key(c["condition"]), c["split"])]
        x[0] += 1
        x[1] += c["scored_s"] / 3600
        x[2] += c["windows"]["5"]
    keys = {k for k, _ in cell}
    assert keys <= {k for k, _ in ROWS}, keys - {k for k, _ in ROWS}

    def fmt(k: str, s: str) -> str:
        n, h, w = cell.get((k, s), (0, 0.0, 0))
        return "-- & -- & --" if n == 0 else f"{n} & {h:.2f} & {w}"

    lines = [r"\begin{tabular}{l" + "rrr" * len(SPLITS) + "}", r"\toprule",
             " & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{$\mathcal{{D}}_{{\mathrm{{{SHORT[s]}}}}}$}}"
                                for s in SPLITS) + r" \\",
             "".join(rf"\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(len(SPLITS))),
             "Workload" + " & runs & h & windows" * len(SPLITS) + r" \\", r"\midrule"]
    for k, name in ROWS:
        lines.append(f"{name} & " + " & ".join(fmt(k, s) for s in SPLITS) + r" \\")
    lines.append(r"\midrule")
    tot = [sum(v[i] for (k, s), v in cell.items() if s == sp) for sp in SPLITS for i in range(3)]
    lines.append("total & " + " & ".join(
        f"{tot[3 * j]} & {tot[3 * j + 1]:.2f} & {tot[3 * j + 2]}" for j in range(len(SPLITS))) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    for j, s in enumerate(SPLITS):
        assert tot[3 * j + 2] == m["totals"]["5"][s], (s, tot[3 * j + 2])
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("% generated by scripts/table_corpus.py from results/windows/manifest.json"
                   f" (repo_commit {m['repo_commit'][:7]}, corpus_commit {m['corpus_commit'][:7]})\n"
                   "% runs, scored hours and 5 s-hop windows per workload and split\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
