"""Number traceability for the manuscript (spec task 8.3).

Every number in the paper's prose is a LaTeX macro whose value is read from a
committed JSON artefact. `paper/numbers.toml` maps each macro to a JSON file and
key path; `render` writes `paper/numbers.tex` from it, and `check` fails on any
digit string left in the prose (outside an explicit allow list) and on a
`numbers.tex` that no longer matches its JSON sources.

Generated tables (`figures/*.tex`) are not checked: their generator scripts are
their provenance.
"""

from __future__ import annotations

import json
import re
import tomllib
from pathlib import Path

HEADER = ("% generated by scripts/paper_numbers.py from paper/numbers.toml;"
          " do not edit by hand\n")


def load_spec(toml_path: Path) -> dict:
    return tomllib.loads(toml_path.read_text())


def _lookup(root: Path, src: str, path: list, cache: dict):
    if src not in cache:
        cache[src] = json.loads((root / src).read_text())
    x = cache[src]
    for k in path:
        x = x[k]
    return x


def _dig(x, path: list):
    for k in path:
        x = x[k]
    return x


_REDUCE = {"min": min, "max": max, "sum": sum}


def raw(entry: dict, root: Path, cache: dict | None = None):
    """Unformatted value of one macro entry.

    Keys: `src`, `path` (list of keys / indices). Optional, applied in order:
    `keys` (keep only these keys of a dict value), `each` (a sub-path read from
    every item of a dict or list value), `reduce` ("min", "max" or "sum" over
    those items), `len` (true: the length of the value), `minus` (a path in the
    same file, or a whole entry, subtracted), `scale` (multiplier).
    """
    cache = {} if cache is None else cache
    v = _lookup(root, entry["src"], entry["path"], cache)
    if "keys" in entry:
        v = {k: v[k] for k in entry["keys"]}
    if "each" in entry or "reduce" in entry:
        items = v.values() if isinstance(v, dict) else v
        v = [_dig(i, entry.get("each", [])) for i in items]
        if "reduce" in entry:
            v = _REDUCE[entry["reduce"]](v)
    if entry.get("len"):
        v = len(v)
    if "minus" in entry:
        m = entry["minus"]
        v = v - (raw({"src": entry["src"], **m}, root, cache) if isinstance(m, dict)
                 else _lookup(root, entry["src"], m, cache))
    if "scale" in entry:
        v = v * entry["scale"]
    return v


def value(entry: dict, root: Path, cache: dict | None = None) -> str:
    """Formatted value of one macro entry: `raw`, then `fmt` (default "{}")."""
    return entry.get("fmt", "{}").format(raw(entry, root, cache))


def render(spec: dict, root: Path) -> str:
    cache: dict = {}
    names = set()
    lines = [HEADER]
    for e in spec.get("n", []):
        name = e["name"]
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name!r}")
        if name in names:
            raise ValueError(f"duplicate macro: {name}")
        names.add(name)
        lines.append(f"\\newcommand{{\\{name}}}{{{value(e, root, cache)}}}"
                     f"  % {e['src']}:{'.'.join(map(str, e['path']))}\n")
    return "".join(lines)


# --- prose check ---------------------------------------------------------------

_STRIP = [
    (re.compile(r"(?<!\\)%.*"), ""),                                   # comments
    (re.compile(r"\\newcommand\{[^}]*\}(\[\d\])?\{.*\}"), ""),           # definitions
    (re.compile(r"\\(?:ref|cref|Cref|eqref|label|cite[pt]?|input|include"
                r"|includegraphics|url|bibliography|bibliographystyle)\*?"
                r"(?:\[[^\]]*\])*\{[^}]*\}"), " "),
    (re.compile(r"\\href\{[^}]*\}"), " "),                              # link target
    (re.compile(r"\\[hv]space\*?\{[^}]*\}"), " "),
    (re.compile(r"\\begin\{(?:figure|table|subfigure|minipage|wrapfigure)\*?\}"
                r"(?:\[[^\]]*\])?(?:\{[^}]*\})?"), " "),
    (re.compile(r"\\\\\[[^\]]*\]"), " "),                               # \\[2pt]
    (re.compile(r"(\\[A-Za-z]+\*?)\[[^\]]*\]"), r"\1"),                 # optional args
]
_NUMBER = re.compile(r"\d+(?:[.,]\d+)*")


def body(tex: str) -> str:
    """The part of a .tex file that is prose: the document body if it has one."""
    m = re.search(r"\\begin\{document\}(.*)\\end\{document\}", tex, re.S)
    return m.group(1) if m else tex


def stray_numbers(tex: str, allow: list[str]) -> list[tuple[int, str, str]]:
    """(line number, number, line) for every digit string not allowed."""
    out = []
    text = body(tex)
    offset = tex[: tex.find(text)].count("\n") if text in tex else 0
    for i, line in enumerate(text.splitlines(), start=1 + offset):
        s = line
        for pat, rep in _STRIP:
            s = pat.sub(rep, s)
        for a in allow:
            s = s.replace(a, " ")
        for m in _NUMBER.finditer(s):
            out.append((i, m.group(0), line.strip()))
    return out


def check(paper: Path, root: Path) -> list[str]:
    """Problems found; empty means the manuscript passes."""
    spec = load_spec(paper / "numbers.toml")
    problems = []
    want = render(spec, root)
    have_path = paper / "numbers.tex"
    if not have_path.exists() or have_path.read_text() != want:
        problems.append("paper/numbers.tex is stale: run scripts/paper_numbers.py")
    allow = spec.get("check", {}).get("allow", [])
    files = [paper / "main.tex", *sorted((paper / "sections").glob("*.tex"))]
    for f in files:
        if not f.exists():
            continue
        for ln, num, line in stray_numbers(f.read_text(), allow):
            problems.append(f"{f.relative_to(paper.parent)}:{ln}: literal {num!r} in: {line}")
    return problems
